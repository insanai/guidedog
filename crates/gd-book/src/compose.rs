//! Composing a book's Typst source (builders.odin's compose_book, write_chapter,
//! book_order and the Typst string helpers): the renderer's preamble, the template,
//! the cover settings, the project's preamble, every chapter of the root's toctree, and
//! the general index.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;

use gd_conf::PdfDocument;
use gd_env::{DocId, OutputFormat};
use gd_host::Ledger;
use gd_link::book_path;
use gd_report::{Report, Severity};
use gd_resolve::BuildView;
use guidedoc::Labels;

use crate::book_index::write_book_index;
use crate::pages::{Job, PageStyle, render_pages};

/// Where a document's chapter lies in the book's source, to trace a problem Typst finds
/// there back to the document.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct ChapterSpan {
    /// The document.
    pub doc: DocId,
    /// Its toctree depth below the book's root.
    pub depth: u32,
    /// Its first byte in the book's source.
    pub start: usize,
    /// The byte after its last.
    pub end: usize,
}

/// A composed book.
#[derive(Debug, Default)]
pub(crate) struct Book {
    /// The book's Typst source.
    pub source: String,
    /// Where each chapter lies in it.
    pub chapters: Vec<ChapterSpan>,
    /// Every file the source reads (images, graphs, the template, the logo), which the
    /// book is rebuilt for when it changes.
    pub files: BTreeSet<PathBuf>,
    /// Chapters that could not be made; the book is then not typeset.
    pub failed: usize,
}

/// What composing a book reads besides the build's view.
pub(crate) struct Composer<'a, 'b> {
    pub view: &'a BuildView<'b>,
    pub labels: Option<&'a Labels>,
    pub ledger: &'a Ledger<'b>,
}

impl Composer<'_, '_> {
    /// Composes the book `book` from the document `root` and its toctree descendants,
    /// adding what reading files and rendering chapters reports to `reports`.
    pub fn compose(&self, book: &PdfDocument, root: DocId, reports: &mut Vec<Report>) -> Book {
        let mut out = Book::default();
        out.source.push_str("// Generated by Guidedog from the project's sources.\n");
        out.source.push_str(guidedoc_typst::PREAMBLE);
        let template = match self.project_template(&mut out, reports) {
            Some(text) => text,
            None => {
                out.source.push_str(gd_theme::BOOK_TYP);
                gd_theme::BOOK_TYP.to_string()
            }
        };
        self.write_cover(&mut out, book, &template);
        self.write_project_preamble(&mut out, reports);
        let order = book_order(self.view, root);
        self.write_chapters(&mut out, root, &order, reports);
        write_book_index(self.view, &mut out.source, &order);
        out
    }

    /// Imports the project's `_templates/book.typ` and returns its text; `None` when the
    /// project has none, or an `--untrusted` build leaves it out (with a warning), as
    /// such a build runs no Typst the project wrote.
    fn project_template(&self, out: &mut Book, reports: &mut Vec<Report>) -> Option<String> {
        let config = self.view.config;
        let path = config.source_dir.join("_templates").join("book.typ");
        if !path.is_file() {
            return None;
        }
        if self.view.options.untrusted {
            let message = "An --untrusted build runs no Typst the project wrote, so the book \
                           uses Guidedog's template.";
            reports.push(Report {
                path: gd_host::display_path(&path.display().to_string()),
                category: "build.untrusted".into(),
                ..Report::warning("build.untrusted", "BOOK TEMPLATE NOT USED", message)
                    .hint("Build without --untrusted if you trust this project.")
            });
            return None;
        }
        let text = self.read_text(&path, reports)?;
        let target = book_path(config, &path);
        let _ = writeln!(out.source, "#import {}: book", typst_string(&target));
        out.files.insert(path);
        Some(text)
    }

    /// The `#show: book.with(...)` line: title, author, version, date, language, paper,
    /// numbering, and the logo, version label and copyright when the template takes them.
    fn write_cover(&self, out: &mut Book, book: &PdfDocument, template: &str) {
        let view = self.view;
        let c = view.config;
        let paper = if matches!(c.pdf.paper_size.as_str(), "letter" | "us-letter") {
            "us-letter"
        } else {
            "a4"
        };
        let title = if book.title.is_empty() { &c.project } else { &book.title };
        let author = if book.author.is_empty() { &c.author } else { &book.author };
        let numbered = view.env.docs.iter().any(|d| d.toctrees.iter().any(|t| t.numbered != 0));
        let mut extra = String::new();
        if !c.pdf.logo.is_empty() {
            let logo = c.source_dir.join(&c.pdf.logo);
            let _ = write!(extra, ", logo: {}", typst_string(&book_path(c, &logo)));
            out.files.insert(logo);
        }
        // Templates written before version-label existed do not take it.
        if template.contains("version-label") {
            let label = view.ui.gettext("Version");
            let _ = write!(extra, ", version-label: {}", typst_string(&label));
        }
        if template.contains("copyright:") && !c.copyright.is_empty() {
            let _ = write!(extra, ", copyright: {}", typst_string(&c.copyright));
        }
        let _ = writeln!(
            out.source,
            "#show: book.with(title: {}, author: {}, version: {}, date: {}, lang: {}, \
             paper: {}, numbering: {numbered}{extra})",
            typst_string(title),
            typst_string(author),
            typst_string(&c.release),
            typst_string(&view.dates.today),
            typst_string(&c.language),
            typst_string(paper),
        );
    }

    /// Adds `pdf_preamble`, the Typst the project wrote to follow the template.
    fn write_project_preamble(&self, out: &mut Book, reports: &mut Vec<Report>) {
        let c = self.view.config;
        if c.pdf.preamble.is_empty() {
            return;
        }
        if let Some(text) = self.read_text(&c.source_dir.join(&c.pdf.preamble), reports) {
            out.source.push_str(&text);
            out.source.push('\n');
        }
    }

    /// Reads a Typst file of the project within the budget; `None`, reported, when it
    /// cannot be read or is not UTF-8.
    fn read_text(&self, path: &std::path::Path, reports: &mut Vec<Report>) -> Option<String> {
        let read = gd_host::read_file(path, Some(self.ledger), gd_host::MAX_SOURCE_BYTES);
        let bytes = read.map_err(|problem| reports.push(problem.report())).ok()?;
        match String::from_utf8(bytes) {
            Ok(text) => Some(text),
            Err(_) => {
                reports.push(not_utf8(path));
                None
            }
        }
    }

    /// Renders the chapters on worker threads and adds them in reading order, each
    /// after a label so references to whole documents have a target.
    fn write_chapters(
        &self,
        out: &mut Book,
        root: DocId,
        order: &[DocId],
        reports: &mut Vec<Report>,
    ) {
        let view = self.view;
        let jobs: Vec<Job> = order
            .iter()
            .filter(|&&id| !view.doc(id).failed)
            .map(|&doc| Job { doc, depth: depth_below(view, doc, root) })
            .collect();
        let style =
            PageStyle { format: OutputFormat::Pdf, renderer: "typst", labels: self.labels };
        let mut pages = jobs.iter().zip(render_pages(view, &jobs, style));
        // In a book of several documents, root sections introduce the chapters. In a
        // standalone document they are the book's navigation and stay in its outline.
        let several = order.len() > 1;
        for &id in order {
            let _ = write!(out.source, "\n#metadata(none) <{}>\n", view.doc_key(id));
            if view.doc(id).failed {
                continue;
            }
            let Some((job, page)) = pages.next() else { break };
            reports.extend(page.reports.iter().cloned());
            let failed = page.failed || !self.charge(&page.body, &view.doc(id).relative, reports);
            if failed {
                out.failed += 1;
                continue;
            }
            out.files.extend(page.assets.into_iter().map(|asset| asset.source));
            let intro = job.depth == 0 && several;
            if intro {
                out.source.push_str("#[\n#set heading(outlined: false)\n");
            }
            let start = out.source.len();
            out.source.push_str(&page.body);
            out.chapters.push(ChapterSpan {
                doc: id,
                depth: job.depth,
                start,
                end: out.source.len(),
            });
            if intro {
                out.source.push_str("\n]\n");
            }
        }
    }

    /// Charges a chapter's place in the book (its text and the source's growth) to the
    /// budget; false, reported, when the budget refuses it.
    fn charge(&self, body: &str, relative: &str, reports: &mut Vec<Report>) -> bool {
        let bytes = 2 * body.len();
        if self.ledger.charge(bytes) {
            return true;
        }
        let what = "Adding this chapter to the book";
        let problem = gd_host::budget_problem(what, relative, bytes, self.ledger.budget());
        reports.push(problem.report());
        false
    }
}

fn not_utf8(path: &std::path::Path) -> Report {
    Report {
        code: "build.pdf.encoding".into(),
        severity: Severity::Error,
        title: "TYPST FILE IS NOT UTF-8".into(),
        message: "This Typst file of the project is not UTF-8 text, so the book leaves it \
                  out."
            .into(),
        hints: vec!["Save the file as UTF-8.".into()],
        path: gd_host::display_path(&path.display().to_string()),
        ..Report::default()
    }
}

/// A document's toctree depth below the book's root (0 for the root).
pub(crate) fn depth_below(view: &BuildView<'_>, doc: DocId, root: DocId) -> u32 {
    let mut depth = 0;
    let mut up = Some(doc);
    // The parents form a tree; the bound only guards against a damaged table.
    for _ in 0..view.tables.order.len() {
        match up {
            Some(id) if id != root => {
                depth += 1;
                up = parent_of(view, id);
            }
            _ => break,
        }
    }
    depth
}

/// The book's documents: the root and its toctree descendants, in reading order.
pub(crate) fn book_order(view: &BuildView<'_>, root: DocId) -> Vec<DocId> {
    let limit = view.tables.order.len();
    let below_root = |id: DocId| {
        let mut up = Some(id);
        for _ in 0..=limit {
            match up {
                Some(at) if at == root => return true,
                Some(at) => up = parent_of(view, at),
                None => return false,
            }
        }
        false
    };
    view.tables.order.iter().copied().filter(|&id| below_root(id)).collect()
}

fn parent_of(view: &BuildView<'_>, id: DocId) -> Option<DocId> {
    view.tables.parent.get(id.index()).copied().flatten()
}

/// Encodes `s` as a Typst string literal: quotes and backslashes escaped, newlines as
/// `\n`, carriage returns and tabs as spaces.
pub fn typst_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' | '\t' => out.push(' '),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Escapes text for Typst markup (a heading's content): every ASCII character with a
/// meaning in markup gets a backslash.
pub fn typst_markup(s: &str) -> String {
    const SPECIAL: &str = "\\#*_`$<>@[]=-+/~\"':.,";
    let mut out = String::with_capacity(s.len() + 8);
    for c in s.chars() {
        if c.is_ascii() && SPECIAL.contains(c) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// A book's file name in a language: `manual.pdf` in German is `manual-de.pdf`; no
/// language counts as `en`. A name that already ends so is kept, and one without an
/// extension gets `.pdf`. Separate names keep several editions side by side.
pub fn language_file(file: &str, language: &str) -> String {
    let lang = if language.is_empty() { "en" } else { language };
    let name_start = file.rfind(['/', '\\']).map_or(0, |i| i + 1);
    let (stem, ext) = match file[name_start..].rfind('.') {
        Some(dot) => file.split_at(name_start + dot),
        None => (file, ""),
    };
    let suffix = format!("-{lang}");
    if stem.ends_with(&suffix) {
        return file.to_string();
    }
    format!("{stem}{suffix}{}", if ext.is_empty() { ".pdf" } else { ext })
}
