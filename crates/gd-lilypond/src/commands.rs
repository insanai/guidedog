/// The explicitly implemented, planned or refused status of a notation command.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CommandStatus {
    /// Fully read and interpreted by the current implementation.
    Implemented,
    /// Listed in the GDS, but not yet implemented; always diagnosed as unsupported.
    Planned,
    /// Metadata accepted without producing marks.
    Ignored,
    /// Engraver programming or constructs outside the profile.
    Refused,
}

/// One command in the versioned Guidedog notation profile.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Command {
    /// Name without its backslash.
    pub name: &'static str,
    /// GDS phase that introduces the construct, or zero for refused commands.
    pub phase: u8,
    /// Explicit current support status.
    pub status: CommandStatus,
}

