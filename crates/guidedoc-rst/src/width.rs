/// The combining marks Odin's `unicode.is_combining` names: the combining diacritical
/// mark blocks.
fn is_combining(c: u32) -> bool {
    matches!(c, 0x0300..=0x036f | 0x1ab0..=0x1aff | 0x1dc0..=0x1dff | 0x20d0..=0x20ff
        | 0xfe20..=0xfe2f)
}

fn is_wide(c: u32) -> bool {
    WIDE.binary_search_by(|&(lo, hi)| {
        if hi < c {
            std::cmp::Ordering::Less
        } else if lo > c {
            std::cmp::Ordering::Greater
        } else {
            std::cmp::Ordering::Equal
        }
    })
    .is_ok()
}

/// The columns character `r` takes.
pub(crate) fn char_columns(r: char) -> usize {
    let c = r as u32;
    if c < 0x80 {
        1
    } else if is_combining(c) {
        0
    } else if is_wide(c) {
        2
    } else {
        1
    }
}

/// The display width of `s` in columns.
pub(crate) fn column_width(s: &str) -> usize {
    s.chars().map(char_columns).sum()
}

