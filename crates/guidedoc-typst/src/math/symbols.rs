//! The table-driven LaTeX commands the adapter supports. Special commands (`\sqrt`,
//! `\left`, `\middle`, `\begin`, `\operatorname`, `\not`, `\pmod`, `\overset`,
//! `\underset`, `\stackrel`, `\boxed`, `\phantom`) and one-character commands are
//! handled in code.

/// How a table command is written.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum CommandKind {
    /// A Typst symbol, operator, or spacing name.
    Symbol,
    /// A style switch Typst decides itself, such as `\displaystyle`.
    Noop,
    /// A command whose argument has no visible form, such as `\label`.
    SkipArg,
    /// `typst` is a call opening such as "hat(" around one argument.
    Wrap,
    /// Like `Wrap`, but a plain word argument becomes one string.
    Font,
    /// A call around two arguments, such as `frac(a, b)`.
    Two,
    /// A text argument as a string, in an optional style call.
    Text,
    /// `\big` and friends: the delimiter at its natural size.
    Delimiter,
}

/// One table command.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Command {
    /// The name without the backslash.
    pub name: &'static str,
    pub kind: CommandKind,
    pub typst: &'static str,
}

const fn cmd(name: &'static str, kind: CommandKind, typst: &'static str) -> Command {
    Command { name, kind, typst }
}

/// Returns the table entry of command `name` (without the backslash).
pub(crate) fn find_command(name: &str) -> Option<&'static Command> {
    COMMANDS.iter().find(|c| c.name == name)
}

