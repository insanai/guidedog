/// The character of the named reference `&name;`, when the table has it.
pub(crate) fn entity(name: &str) -> Option<char> {
    ENTITIES.binary_search_by(|e| e.0.cmp(name)).ok().map(|at| ENTITIES[at].1)
}

/// Characters that are written as nothing: MathML's invisible operators (function
/// application, invisible times, separator and plus) and zero-width marks.
pub(crate) fn is_invisible(c: char) -> bool {
    matches!(c, '\u{2061}'..='\u{2064}' | '\u{200b}'..='\u{200d}' | '\u{feff}')
}

/// The Typst call that sets `base` under the accent character `c` of an `mover`.
pub(crate) fn over_accent(c: char) -> Option<&'static str> {
    Some(match c {
        '^' | 'ˆ' | '\u{302}' => "hat(",
        '~' | '˜' | '∼' | '\u{303}' => "tilde(",
        '¯' | 'ˉ' | '\u{304}' => "macron(",
        '‾' | '―' | '─' | '\u{305}' => "overline(",
        '→' | '⟶' | '\u{20d7}' => "arrow(",
        '.' | '˙' | '\u{307}' => "dot(",
        '¨' | '\u{308}' => "dot.double(",
        'ˇ' | '\u{30c}' => "caron(",
        '˘' | '\u{306}' => "breve(",
        '´' | '\u{301}' => "acute(",
        '`' | '\u{300}' => "grave(",
        '⏞' => "overbrace(",
        _ => return None,
    })
}

/// The Typst call that sets `base` over the accent character `c` of an `munder`.
pub(crate) fn under_accent(c: char) -> Option<&'static str> {
    Some(match c {
        '_' | '¯' | '‾' | '―' | '─' | '\u{332}' => "underline(",
        '⏟' => "underbrace(",
        _ => return None,
    })
}

/// The closing fence that pairs with the opening fence `open`.
pub(crate) fn closing_fence(open: char) -> Option<char> {
    Some(match open {
        '(' => ')',
        '[' => ']',
        '{' => '}',
        '|' => '|',
        '‖' => '‖',
        '⟨' => '⟩',
        '⌊' => '⌋',
        '⌈' => '⌉',
        _ => return None,
    })
}

/// Tells whether `c` closes a fenced group.
pub(crate) fn is_closing_fence(c: char) -> bool {
    matches!(c, ')' | ']' | '}' | '|' | '‖' | '⟩' | '⌋' | '⌉')
}

/// The Typst calls of a `mathvariant` value, such as "bold(italic("; `None` for a
/// value Typst has no style for, which then changes nothing.
pub(crate) fn variant_call(variant: &str) -> Option<&'static str> {
    Some(match variant {
        "normal" => "upright(",
        "bold" => "bold(",
        "italic" => "italic(",
        "bold-italic" => "bold(italic(",
        "double-struck" => "bb(",
        "script" => "cal(",
        "bold-script" => "bold(cal(",
        "fraktur" => "frak(",
        "bold-fraktur" => "bold(frak(",
        "sans-serif" => "sans(",
        "bold-sans-serif" => "bold(sans(",
        "sans-serif-italic" => "italic(sans(",
        "sans-serif-bold-italic" => "bold(italic(sans(",
        "monospace" => "mono(",
        _ => return None,
    })
}
