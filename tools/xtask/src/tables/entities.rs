//! The HTML5 named character references CommonMark recognizes, from WHATWG's
//! `entities.json` in `tools/data`.

use std::fmt::Write;
use std::path::Path;

use super::Table;
use super::pack::{WIDTH, pack};
use crate::fsutil::read_text;
use crate::{Result, fail};

/// The entity list's file in `tools/data`.
const SOURCE: &str = "entities.json";

/// Generates `entity_table.rs`: every name that ends in ";", without "&" and ";", with
/// the characters it stands for, sorted by name.
pub(super) fn generate(data: &Path) -> Result<Vec<Table>> {
    let path = data.join(SOURCE);
    let text = read_text(&path)?;
    let json = gd_json::parse(&text).map_err(|err| {
        let report = err.report(&path.display().to_string(), &text);
        crate::Failure { report: Box::new(report), usage: false }
    })?;
    let Some(object) = json.as_object() else {
        return Err(not_entities(&path, "it is not a JSON object"));
    };
    let mut entities = Vec::new();
    for (key, value) in object {
        let Some(name) = key.strip_prefix('&').and_then(|k| k.strip_suffix(';')) else {
            continue;
        };
        let codes = value.get("codepoints").and_then(|c| c.as_array());
        let mut characters = String::new();
        for code in codes.into_iter().flatten() {
            let c = code.as_u64().and_then(|c| u32::try_from(c).ok()).and_then(char::from_u32);
            let Some(c) = c else { return Err(not_entities(&path, &format!("{key} is odd"))) };
            characters.push(c);
        }
        entities.push((name.to_string(), characters));
    }
    entities.sort();
    let mut out = String::from(
        "//! The HTML5 named character references (WHATWG `entities.json`, the names that end\n\
         //! in \";\"), as CommonMark 0.31.2 recognizes them. Generated by `cargo xtask tables`\n\
         //! from tools/data/entities.json; do not edit.\n\n\
         /// Each name without \"&\" and \";\", with the characters it stands for; \
         sorted by name.\n\
         #[rustfmt::skip] // One row per table entry would pass the file-length limit.\n\
         pub(crate) const ENTITIES: &[(&str, &str)] = &[\n",
    );
    let items =
        entities.iter().map(|(name, chars)| format!("(\"{name}\", \"{}\"),", escape(chars)));
    pack(&mut out, "    ", WIDTH, items);
    out.push_str("];\n");
    let target = "crates/guidedoc-commonmark/src/inline/entity_table.rs";
    Ok(vec![Table::new(target.to_string(), out)])
}

/// A Rust string literal's contents: printable ASCII as itself (with `\` and `"`
/// escaped), everything else as `\u{..}`.
fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len() * 2);
    for c in text.chars() {
        match c {
            '\\' | '"' => {
                out.push('\\');
                out.push(c);
            }
            ' '..='~' => out.push(c),
            _ => {
                let _ = write!(out, "\\u{{{:X}}}", u32::from(c));
            }
        }
    }
    out
}

fn not_entities(path: &Path, why: &str) -> crate::Failure {
    fail(
        "tables-data",
        "UNEXPECTED DATA",
        &format!("{} is not WHATWG's entity list: {why}.", path.display()),
        "Download https://html.spec.whatwg.org/entities.json again into tools/data.",
    )
}
