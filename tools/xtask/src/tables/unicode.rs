//! The Unicode tables: case folding, identifier folding, canonical decomposition,
//! general-category ranges, and the punctuation and white space of reStructuredText's
//! inline markup, from the Unicode Character Database files in `tools/data`.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;

use super::Table;
use super::pack::pack;
use crate::Result;
use crate::fsutil::read_text;

/// The Unicode version of the data files.
const VERSION: &str = "17.0.0";

/// The widest line of the Unicode tables; the committed tables are laid out to it.
const WIDTH: usize = 96;

/// The line every generated Unicode table names its generator with.
const GENERATED: &str = "//! Generated by `cargo xtask tables`; do not edit.\n";

/// The comment the packed tables carry on their `#[rustfmt::skip]`.
const SKIP: &str =
    "#[rustfmt::skip] // One row per table entry would pass the file-length limit.\n";

/// One line of UnicodeData.txt, borrowing its fields.
struct Record<'a> {
    code: u32,
    name: &'a str,
    category: &'a str,
    class: u8,
    bidi: &'a str,
    decomposition: &'a str,
}

/// An inclusive range of characters with a property.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Range<'a> {
    lo: u32,
    hi: u32,
    property: &'a str,
}

/// Generates every Unicode table from the files in `data`.
pub(super) fn generate(data: &Path) -> Result<Vec<Table>> {
    let unicode_data = read_text(&data.join(format!("UnicodeData-{VERSION}.txt")))?;
    let categories = read_text(&data.join(format!("DerivedGeneralCategory-{VERSION}.txt")))?;
    let folding = read_text(&data.join(format!("CaseFolding-{VERSION}.txt")))?;
    let records = read_records(&unicode_data);
    let ranges = read_categories(&categories);
    let core = "crates/guidedoc/src/tables";
    let mut tables = vec![
        Table::new(format!("{core}/casefold.rs"), case_folds(&folding)),
        Table::new(format!("{core}/categories.rs"), category_tables(&ranges)),
        Table::new(format!("{core}/idfold.rs"), id_folds(&records)),
    ];
    let (decompositions, runes) = decomposition_tables(&records);
    tables.push(Table::new(format!("{core}/nfd_classes.rs"), combining_classes(&records)));
    tables.push(Table::new(format!("{core}/nfd_decompositions.rs"), decompositions));
    tables.push(Table::new(format!("{core}/nfd_runes.rs"), runes));
    tables.push(Table::new(
        "crates/guidedoc-rst-inline/src/punctuation_table.rs".to_string(),
        punctuation(&ranges, &records),
    ));
    Ok(tables)
}

fn hex(field: &str) -> u32 {
    u32::from_str_radix(field.trim(), 16).unwrap_or(0)
}

fn read_records(text: &str) -> Vec<Record<'_>> {
    let mut records = Vec::with_capacity(40_000);
    for line in text.lines() {
        let f: Vec<&str> = line.split(';').collect();
        if f.len() < 6 {
            continue;
        }
        records.push(Record {
            code: hex(f[0]),
            name: f[1],
            category: f[2],
            class: f[3].parse().unwrap_or(0),
            bidi: f[4],
            decomposition: f[5],
        });
    }
    records
}

/// The ranges of DerivedGeneralCategory.txt with their categories, sorted.
fn read_categories(text: &str) -> Vec<Range<'_>> {
    let mut ranges = Vec::new();
    for line in text.lines() {
        let body = line.split('#').next().unwrap_or_default();
        let Some((codes, category)) = body.split_once(';') else { continue };
        let (lo, hi) = match codes.trim().split_once("..") {
            Some((lo, hi)) => (hex(lo), hex(hi)),
            None => (hex(codes), hex(codes)),
        };
        ranges.push(Range { lo, hi, property: category.trim() });
    }
    ranges.sort_by_key(|r| r.lo);
    ranges
}

/// Joins adjacent ranges; with `same_property`, only those of one property.
fn merge<'a>(ranges: impl IntoIterator<Item = Range<'a>>, same_property: bool) -> Vec<Range<'a>> {
    let mut merged: Vec<Range<'a>> = Vec::new();
    for r in ranges {
        if let Some(last) = merged.last_mut()
            && last.hi + 1 == r.lo
            && (!same_property || last.property == r.property)
        {
            last.hi = r.hi;
            continue;
        }
        merged.push(r);
    }
    merged
}

fn case_folds(text: &str) -> String {
    let mut out = format!(
        "//! Unicode full case folding (statuses C and F), from CaseFolding-{VERSION}.txt.\n\
         {GENERATED}\n\
         /// Each character with its folding; unused slots are zero, sorted by character.\n\
         {SKIP}pub(crate) const CASE_FOLDS: &[(u32, [u32; 3])] = &[\n"
    );
    let items = text.lines().filter_map(|line| {
        let fields: Vec<&str> = line.split("; ").collect();
        if line.starts_with('#') || fields.len() < 3 || !matches!(fields[1], "C" | "F") {
            return None;
        }
        let mut to = [0u32; 3];
        for (slot, code) in to.iter_mut().zip(fields[2].split_whitespace()) {
            *slot = hex(code);
        }
        let [a, b, c] = to;
        Some(format!("(0x{:X}, [0x{a:X}, 0x{b:X}, 0x{c:X}]),", hex(fields[0])))
    });
    pack(&mut out, "    ", WIDTH, items);
    out.push_str("];\n");
    out
}

/// Whether a general category belongs to a table.
type CategoryTest = fn(&str) -> bool;

fn category_tables(ranges: &[Range<'_>]) -> String {
    let mut out = format!(
        "//! General-category ranges from DerivedGeneralCategory-{VERSION}.txt.\n{GENERATED}"
    );
    let groups: [(&str, &str, CategoryTest); 3] = [
        (
            "General categories P and S (CommonMark's Unicode punctuation)",
            "PUNCTUATION_OR_SYMBOL",
            |c| c.starts_with('P') || c.starts_with('S'),
        ),
        ("General category L", "LETTERS", |c| c.starts_with('L')),
        ("General category Nd", "DECIMAL_DIGITS", |c| c == "Nd"),
    ];
    for (doc, name, wanted) in groups {
        let chosen = ranges.iter().copied().filter(|r| wanted(r.property));
        let _ = write!(
            out,
            "\n/// {doc}. Inclusive ranges, sorted.\n\
             {SKIP}pub(crate) const {name}: &[(u32, u32)] = &[\n"
        );
        pack(
            &mut out,
            "    ",
            WIDTH,
            merge(chosen, false).iter().map(|r| format!("(0x{:X}, 0x{:X}),", r.lo, r.hi)),
        );
        out.push_str("];\n");
    }
    out
}

/// Spellings that existing documentation URLs already use, kept over the derived ones.
const DIGRAPHS: [(u32, &str); 7] = [
    (0xDF, "sz"),
    (0xE6, "ae"),
    (0x153, "oe"),
    (0x238, "db"),
    (0x239, "qp"),
    (0xC6, "ae"),
    (0x152, "oe"),
];

/// For each character from U+0080 on, the ASCII letters and digits it stands for in an
/// identifier: the ASCII part of its full compatibility decomposition, else the base
/// letter of a "LATIN ... LETTER X WITH ..." or dotless letter. Characters that stand
/// for nothing but a separator are left out, since make_id treats unlisted ones so.
fn id_folds(records: &[Record<'_>]) -> String {
    let by_code: BTreeMap<u32, &Record<'_>> = records.iter().map(|r| (r.code, r)).collect();
    let mut out = format!(
        "//! ASCII transliterations make_id gives lowercase characters, from \
         UnicodeData-{VERSION}.txt.\n{GENERATED}\n\
         /// Each character with its transliteration, sorted by character.\n\
         {SKIP}pub(crate) const ID_FOLDS: &[(u32, &str)] = &[\n"
    );
    let items = by_code.range(0x80..).filter_map(|(&code, record)| {
        let mut ascii = String::new();
        fold_ascii(&by_code, code, 0, &mut ascii);
        if let Some((_, spelling)) = DIGRAPHS.iter().find(|(from, _)| *from == code) {
            ascii = spelling.to_string();
        }
        if ascii.is_empty() {
            ascii = letter_by_name(record.name);
        }
        (!ascii.trim().is_empty()).then(|| format!("(0x{code:X}, \"{ascii}\"),"))
    });
    pack(&mut out, "    ", WIDTH, items);
    out.push_str("];\n");
    out
}

/// Appends the lowercase ASCII letters, digits and spaces of a character's full
/// decomposition (compatibility ones too), giving up below a depth of eight.
fn fold_ascii(by_code: &BTreeMap<u32, &Record<'_>>, code: u32, depth: u32, out: &mut String) {
    if code < 0x80 {
        let c = char::from(code as u8);
        if c.is_ascii_lowercase() || c.is_ascii_digit() || c == ' ' {
            out.push(c);
        } else if c.is_ascii_uppercase() {
            out.push(c.to_ascii_lowercase());
        }
        return;
    }
    let Some(record) = by_code.get(&code) else { return };
    if depth > 8 {
        return;
    }
    let parts = record.decomposition.split_whitespace().filter(|p| !p.starts_with('<'));
    for part in parts {
        fold_ascii(by_code, hex(part), depth + 1, out);
    }
}

/// The base letter of "LATIN SMALL LETTER A WITH GRAVE" or "LATIN SMALL LETTER DOTLESS
/// I", in lowercase; empty for other names.
fn letter_by_name(name: &str) -> String {
    for prefix in ["LATIN SMALL LETTER ", "LATIN CAPITAL LETTER "] {
        let Some(rest) = name.strip_prefix(prefix) else { continue };
        if let Some(letter) = rest.strip_prefix("DOTLESS ")
            && letter.len() == 1
        {
            return letter.to_lowercase();
        }
        let (letter, tail) = rest.split_once(' ').unwrap_or((rest, ""));
        if letter.len() == 1 && tail.starts_with("WITH ") {
            return letter.to_lowercase();
        }
    }
    String::new()
}

/// The canonical decomposition of every character that has one, fully applied: the
/// `NFD_DECOMPOSITIONS` index and the `NFD_RUNES` it points into. Hangul syllables
/// decompose by algorithm, and UnicodeData.txt lists none for them.
fn decomposition_tables(records: &[Record<'_>]) -> (String, String) {
    let canonical: BTreeMap<u32, Vec<u32>> = records
        .iter()
        .filter(|r| !r.decomposition.is_empty() && !r.decomposition.starts_with('<'))
        .map(|r| (r.code, r.decomposition.split_whitespace().map(hex).collect()))
        .collect();
    let mut runes = Vec::new();
    let mut index = Vec::with_capacity(canonical.len());
    for &code in canonical.keys() {
        let start = runes.len();
        decompose(&canonical, code, &mut runes);
        index.push(format!("(0x{code:X}, {start}, {}),", runes.len() - start));
    }
    let source = format!("UnicodeData-{VERSION}.txt");
    let mut decompositions = format!(
        "//! Full canonical decompositions, from {source}.\n{GENERATED}\n\
         /// Each character's decomposition as a start and length in `NFD_RUNES`, sorted.\n\
         {SKIP}pub(crate) const NFD_DECOMPOSITIONS: &[(u32, u16, u16)] = &[\n"
    );
    pack(&mut decompositions, "    ", WIDTH, index);
    decompositions.push_str("];\n");
    let mut table = format!(
        "//! The characters of every canonical decomposition, from {source}.\n{GENERATED}\n\
         /// Decomposed characters, indexed by `NFD_DECOMPOSITIONS`.\n\
         {SKIP}pub(crate) const NFD_RUNES: &[u32] = &[\n"
    );
    pack(&mut table, "    ", WIDTH, runes.iter().map(|r| format!("0x{r:X},")));
    table.push_str("];\n");
    (decompositions, table)
}

/// Applies canonical decompositions until none is left.
fn decompose(canonical: &BTreeMap<u32, Vec<u32>>, code: u32, out: &mut Vec<u32>) {
    match canonical.get(&code) {
        Some(parts) => parts.iter().for_each(|&part| decompose(canonical, part, out)),
        None => out.push(code),
    }
}

fn combining_classes(records: &[Record<'_>]) -> String {
    let mut out = format!(
        "//! Canonical combining classes other than 0, from UnicodeData-{VERSION}.txt.\n\
         {GENERATED}\n/// Each combining character with its class, sorted by character.\n\
         {SKIP}pub(crate) const NFD_CLASSES: &[(u32, u8)] = &[\n"
    );
    let mut marks: Vec<(u32, u8)> =
        records.iter().filter(|r| r.class != 0).map(|r| (r.code, r.class)).collect();
    marks.sort_unstable();
    pack(
        &mut out,
        "    ",
        WIDTH,
        marks.iter().map(|(code, class)| format!("(0x{code:X}, {class}),")),
    );
    out.push_str("];\n");
    out
}

/// The punctuation categories of inline markup recognition, and white space as Python's
/// `str.isspace` defines it (category Zs, or bidirectional class WS, B or S).
fn punctuation(ranges: &[Range<'_>], records: &[Record<'_>]) -> String {
    let mut out = format!(
        "//! Generated by `cargo xtask tables` from DerivedGeneralCategory-{VERSION}.txt and\n\
         //! UnicodeData-{VERSION}.txt; do not edit.\n\n\
         use crate::chars::GeneralPunctuation::{{self, Pc, Pd, Pe, Pf, Pi, Po, Ps}};\n\n\
         /// Punctuation ranges `(lo, hi, category)`, sorted.\n#[rustfmt::skip]\n\
         pub(crate) const PUNCTUATION: &[(u32, u32, GeneralPunctuation)] = &[\n"
    );
    let categories = ["Ps", "Pe", "Pi", "Pf", "Pd", "Po", "Pc"];
    let chosen = ranges.iter().copied().filter(|r| categories.contains(&r.property));
    let items = merge(chosen, true)
        .into_iter()
        .map(|r| format!("(0x{:X}, 0x{:X}, {}),", r.lo, r.hi, r.property));
    pack(&mut out, "    ", WIDTH, items);
    out.push_str(
        "];\n\n/// White space as Python's `str.isspace`, as `(lo, hi)` ranges.\n\
         pub(crate) const SPACES: &[(u32, u32)] = &[\n",
    );
    for r in merge(spaces(records), true) {
        let _ = writeln!(out, "    (0x{:X}, 0x{:X}),", r.lo, r.hi);
    }
    out.push_str("];\n");
    out
}

/// The white space of UnicodeData.txt, whose "<..., First>" and "<..., Last>" lines
/// bound a range of characters sharing one line's properties.
fn spaces<'a>(records: &[Record<'a>]) -> Vec<Range<'a>> {
    let mut found = Vec::new();
    let mut first = None;
    for r in records {
        if r.name.ends_with(", First>") {
            first = Some(r.code);
            continue;
        }
        let lo = match first.take() {
            Some(lo) if r.name.ends_with(", Last>") => lo,
            _ => r.code,
        };
        if r.category == "Zs" || matches!(r.bidi, "WS" | "B" | "S") {
            found.push(Range { lo, hi: r.code, property: "space" });
        }
    }
    found
}
